from datetime import date

# 1. String Variable (Best for simple, human-readable display)
birthday_string = "October 31, 1995"

# 2. Dictionary Variable (Best for looking up a specific person's birthday)
birthday_dict = {"Alice": "1998-05-14", "Bob": "1993-09-22"}

# 3. List Variable (Best if you have an ordered sequence of dates)
birthday_list = ["January 1", "July 4", "December 25"]

# 4. Tuple Variable (Best for data that should never be changed or edited)
birthday_tuple = (1990, 12, 15)  # (Year, Month, Day)

# 5. Datetime Object Variable (Best for calculating age or countdowns)
birthday_object = date(2001, 8, 26) 